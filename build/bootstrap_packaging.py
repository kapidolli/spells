"""Bootstrap the packaging toolchain into build/toolchain (spec 19.3 steps 5 and 7).

Usage:
    py build/bootstrap_packaging.py

No admin, no registry, no PATH changes, nothing outside the repo, exactly like
build/bootstrap_toolchain.py (spec 19.2). The sequence is:

1. fetch and hash-check the pinned innoextract Windows zip (build/fetch.py) and unpack it into
   build/toolchain/innoextract/
2. fetch and hash-check the pinned Inno Setup 6 installer, then unpack its ``{app}`` files with
   innoextract into build/toolchain/innosetup/. The installer is never executed: a standard user
   cannot install into Program Files, and spec 19.2 wants the whole toolchain inside the repo.
   That also means no uninstall entry, no registry key and no shell association is created
3. run ``ISCC.exe /?`` and check the banner reports the pinned major version
4. compile a tiny throwaway script with ``PrivilegesRequired=lowest`` into
   build/out/smoke-setup.exe, check the compiler engine version the compile prints against the
   pin, then delete the produced exe. It is only ever compiled, never run
5. install the pinned PyInstaller wheel into .venv and check ``-m PyInstaller --version``
6. build a one-folder smoke app into build/out/pyinstaller-smoke/, run it once to prove the
   bootloader starts on this machine, then delete it

Rerunning skips whatever is already in place; steps 3 to 6 are verifications and always run, so
a second run does nothing but verify. Smart App Control can block an unsigned file the first
time it is seen (innoextract.exe and the PyInstaller bootloader are unsigned), so every native
tool goes through build/bootstrap_toolchain.py's ``run_tool``, which retries once the cloud
verdict is cached and names a file that stays blocked.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bootstrap_toolchain as toolchain
import fetch

REPO_DIR = Path(__file__).resolve().parents[1]
BUILD_DIR = REPO_DIR / "build"
CACHE_DIR = BUILD_DIR / "cache"
OUT_DIR = BUILD_DIR / "out"
TOOLCHAIN_ROOT = BUILD_DIR / "toolchain"
VENV_PYTHON = REPO_DIR / ".venv" / "Scripts" / "python.exe"

INNO_SETUP_KEY = "toolchain.inno_setup"
INNOEXTRACT_KEY = "toolchain.innoextract"
PYINSTALLER_KEY = "toolchain.pyinstaller"

INNOEXTRACT_SUBDIR = "innoextract"
INNOSETUP_SUBDIR = "innosetup"
INNOEXTRACT_DIR = TOOLCHAIN_ROOT / INNOEXTRACT_SUBDIR
INNOEXTRACT_EXE = INNOEXTRACT_DIR / "innoextract.exe"
INNOSETUP_DIR = TOOLCHAIN_ROOT / INNOSETUP_SUBDIR
ISCC_EXE = INNOSETUP_DIR / "ISCC.exe"
STAGE_DIR = TOOLCHAIN_ROOT / "innosetup-stage"
SMOKE_DIR = TOOLCHAIN_ROOT / "packaging-smoke"
PYINSTALLER_SMOKE_DIR = OUT_DIR / "pyinstaller-smoke"

# What has to be on disk for a part to count as installed. ISCC.exe alone cannot compile: the
# compiler and preprocessor DLLs, the default message file, the two setup stubs it stamps into
# every installer and the compression helpers all live beside it in the installer's {app} folder.
INNOEXTRACT_FILES = ("innoextract.exe",)
INNOSETUP_FILES = (
    "ISCC.exe", "ISCmplr.dll", "ISPP.dll", "ISPPBuiltins.iss", "Default.isl",
    "Setup.e32", "SetupLdr.e32", "islzma.dll", "islzma32.exe", "islzma64.exe",
    "isbzip.dll", "isbunzip.dll", "iszlib.dll", "isunzlib.dll",
)
PARTS = {
    "innoextract": (INNOEXTRACT_SUBDIR, INNOEXTRACT_FILES),
    "innosetup": (INNOSETUP_SUBDIR, INNOSETUP_FILES),
}

SMOKE_SETUP_BASENAME = "smoke-setup"
SMOKE_APP_NAME = "pyinstaller-smoke"
SMOKE_APP_MARKER = "spells pyinstaller smoke ok"
SMOKE_APP_SOURCE = (
    "import sys\n"
    f'print("{SMOKE_APP_MARKER}", sys.version_info[0], sys.version_info[1])\n'
)

# innoextract writes the installer's {app} files into this subdirectory of its output directory.
EXTRACTED_APP_SUBDIR = "app"

SMOKE_ISS_TEMPLATE = """\
; Generated by build/bootstrap_packaging.py to prove the Inno Setup compiler works (19.3 step 7).
; The compiled installer is deleted right after the compile and is never run.
[Setup]
AppName=Spells packaging smoke test
AppVersion=0.0.0
PrivilegesRequired=lowest
DefaultDirName={{localappdata}}\\Programs\\SpellsPackagingSmoke
OutputDir={output_dir}
OutputBaseFilename={output_basename}
Uninstallable=no
Compression=lzma2/fast
SolidCompression=no

[Files]
Source: "{payload}"; DestDir: "{{app}}"
"""

ISCC_ENGINE_RE = re.compile(r"Compiler engine version:\s*Inno Setup\s+(\d+(?:\.\d+)*)")
ISCC_BANNER_RE = re.compile(r"Inno Setup\s+(\d+(?:\.\d+)*)\s+Command-Line Compiler")
PYINSTALLER_VERSION_RE = re.compile(r"^[ \t]*(\d+(?:\.\d+)+\S*)[ \t]*$", re.MULTILINE)


class PackagingError(Exception):
    pass


# ----------------------------------------------------------------------------- pure helpers


def smoke_iss_text(*, output_dir: Path | str, output_basename: str, payload: Path | str) -> str:
    """The throwaway Inno Setup script of step 4, compiled and then deleted."""
    return SMOKE_ISS_TEMPLATE.format(
        output_dir=output_dir, output_basename=output_basename, payload=payload)


def parse_iscc_version(output: str | None) -> str | None:
    """The Inno Setup version ISCC reports, or None.

    A compile prints ``Compiler engine version: Inno Setup 6.2.2``, which is exact. ``/?`` only
    prints the banner ``Inno Setup 6 Command-Line Compiler``, so that path yields the major
    version. The exact line wins when both are present.
    """
    text = output or ""
    for pattern in (ISCC_ENGINE_RE, ISCC_BANNER_RE):
        match = pattern.search(text)
        if match:
            return match.group(1)
    return None


def parse_pyinstaller_version(output: str | None) -> str | None:
    """The version from ``python -m PyInstaller --version``, which prints it on a line of its own."""
    match = PYINSTALLER_VERSION_RE.search(output or "")
    return match.group(1) if match else None


def version_agrees(reported: str | None, pinned: str | None) -> bool:
    """True when ``reported`` is ``pinned`` truncated at a dot, so "6" agrees with "6.2.2"."""
    if not reported or not pinned:
        return False
    got = reported.split(".")
    want = pinned.split(".")
    return len(got) <= len(want) and got == want[:len(got)]


def missing_parts(toolchain_root: Path) -> dict[str, list[str]]:
    """Which files each part is missing; an empty dict means there is nothing left to install."""
    result: dict[str, list[str]] = {}
    for part, (subdir, names) in PARTS.items():
        folder = Path(toolchain_root) / subdir
        missing = [name for name in names if not (folder / name).is_file()]
        if missing:
            result[part] = missing
    return result


def innoextract_args(exe: Path, installer: Path, output_dir: Path) -> list[str]:
    """Unpack only: innoextract reads the installer as an archive and never executes it."""
    return [str(exe), "--extract", "--silent", "--output-dir", str(output_dir), str(installer)]


def pyinstaller_args(python_exe: Path, script: Path, *, dist_dir: Path, work_dir: Path,
                     name: str) -> list[str]:
    """One folder, no UPX, per spec 19.3 step 5."""
    return [
        str(python_exe), "-m", "PyInstaller", "--onedir", "--noconfirm", "--noupx",
        "--log-level", "WARN",
        "--distpath", str(dist_dir), "--workpath", str(work_dir), "--specpath", str(work_dir),
        "--name", name, str(script),
    ]


def pinned_version(key: str) -> str:
    return fetch.resolve(fetch.load_pins(), key)["version"]


# ----------------------------------------------------------------------------- extraction


def extract_zip(archive: Path, dest: Path) -> None:
    """Extract every member of ``archive`` under ``dest``, refusing a member that escapes it."""
    dest.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive) as zf:
        for member in zf.infolist():
            if member.is_dir():
                continue
            name = member.filename.replace("\\", "/")
            if name.startswith("/") or ".." in name.split("/") or ":" in name:
                raise PackagingError(f"{archive.name}: refusing the member name {member.filename!r}")
            target = dest / Path(name)
            target.parent.mkdir(parents=True, exist_ok=True)
            with zf.open(member) as src, open(target, "wb") as out:
                shutil.copyfileobj(src, out)


def ensure_innoextract() -> None:
    if "innoextract" not in missing_parts(TOOLCHAIN_ROOT):
        print(f"innoextract: {INNOEXTRACT_DIR} already in place")
        return
    archive = fetch.fetch(INNOEXTRACT_KEY)
    print(f"innoextract: extracting {archive.name} into {INNOEXTRACT_DIR}")
    extract_zip(archive, INNOEXTRACT_DIR)
    still = missing_parts(TOOLCHAIN_ROOT).get("innoextract")
    if still:
        raise PackagingError(f"{INNOEXTRACT_DIR} is missing {', '.join(still)} after extraction")


def ensure_innosetup() -> None:
    """Unpack the pinned Inno Setup installer's {app} files without running the installer."""
    if "innosetup" not in missing_parts(TOOLCHAIN_ROOT):
        print(f"inno setup: {INNOSETUP_DIR} already in place")
        return
    installer = fetch.fetch(INNO_SETUP_KEY)
    shutil.rmtree(STAGE_DIR, ignore_errors=True)
    args = innoextract_args(INNOEXTRACT_EXE, installer, STAGE_DIR)
    print("+ " + " ".join(args), flush=True)
    result = toolchain.run_tool(args, cwd=TOOLCHAIN_ROOT, env=toolchain.clean_windows_env())
    output = (result.stdout + result.stderr).strip()
    if output:
        print(output, flush=True)
    app_dir = STAGE_DIR / EXTRACTED_APP_SUBDIR
    if not app_dir.is_dir():
        raise PackagingError(
            f"innoextract produced no {EXTRACTED_APP_SUBDIR} directory in {STAGE_DIR}. The pinned "
            f"innoextract release may not understand this Inno Setup version.")
    shutil.rmtree(INNOSETUP_DIR, ignore_errors=True)
    INNOSETUP_DIR.parent.mkdir(parents=True, exist_ok=True)
    app_dir.replace(INNOSETUP_DIR)
    shutil.rmtree(STAGE_DIR, ignore_errors=True)
    still = missing_parts(TOOLCHAIN_ROOT).get("innosetup")
    if still:
        raise PackagingError(f"{INNOSETUP_DIR} is missing {', '.join(still)} after extraction")
    print(f"inno setup: unpacked into {INNOSETUP_DIR} (the installer was never run)")


# ----------------------------------------------------------------------------- verification


def verify_iscc(pinned: str) -> str:
    """``ISCC.exe /?`` prints its banner; check the version in it against the pin.

    ``/?`` is the usage screen, and ISCC exits with code 1 after printing it, so the banner is
    what is checked here rather than the exit code. That is also why this one call does not go
    through ``run_tool``, which treats a nonzero exit as a failure; a code integrity block is
    still recognised and reported.
    """
    try:
        result = subprocess.run([str(ISCC_EXE), "/?"], cwd=str(INNOSETUP_DIR),
                                env=toolchain.clean_windows_env(), capture_output=True, text=True,
                                encoding="utf-8", errors="replace", check=False)
    except OSError as exc:
        if toolchain.is_policy_block(exc):
            raise PackagingError(
                f"Windows code integrity blocked {ISCC_EXE} ({exc}). Smart App Control does not "
                f"accept this file; see Windows Security > App & browser control.") from exc
        raise
    text = result.stdout or result.stderr
    version = parse_iscc_version(text)
    if not version_agrees(version, pinned):
        raise PackagingError(
            f"ISCC.exe /? reported version {version!r}, which does not agree with the pinned "
            f"{pinned!r}. First line: {text.strip().splitlines()[0] if text.strip() else '(none)'}")
    print(f"  ISCC.exe /? banner reports Inno Setup {version} (pinned {pinned})   [{ISCC_EXE}]")
    return version


def compile_smoke_installer(pinned: str) -> str:
    """Compile a throwaway PrivilegesRequired=lowest installer, then delete it. Never run it."""
    shutil.rmtree(SMOKE_DIR, ignore_errors=True)
    SMOKE_DIR.mkdir(parents=True, exist_ok=True)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    payload = SMOKE_DIR / "payload.txt"
    payload.write_text("Spells packaging smoke payload\n", encoding="utf-8")
    script = SMOKE_DIR / "smoke.iss"
    script.write_text(
        smoke_iss_text(output_dir=OUT_DIR, output_basename=SMOKE_SETUP_BASENAME, payload=payload),
        encoding="utf-8", newline="\r\n")

    result = toolchain.run_tool([str(ISCC_EXE), str(script)], cwd=SMOKE_DIR,
                                env=toolchain.clean_windows_env())
    produced = OUT_DIR / f"{SMOKE_SETUP_BASENAME}.exe"
    if not produced.is_file():
        raise PackagingError(f"ISCC reported success but {produced} is missing")
    version = parse_iscc_version(result.stdout)
    if version != pinned:
        raise PackagingError(f"the compile reported engine version {version!r}, pinned {pinned!r}")
    size = produced.stat().st_size
    produced.unlink()
    shutil.rmtree(SMOKE_DIR, ignore_errors=True)
    print(f"  compiled {produced.name} ({size} bytes) with engine version {version}, "
          f"then deleted it; it was never run")
    return version


# ----------------------------------------------------------------------------- pyinstaller


def installed_pyinstaller_version() -> str | None:
    if not VENV_PYTHON.is_file():
        raise PackagingError(f"{VENV_PYTHON} is missing; create the project virtual environment first")
    result = subprocess.run([str(VENV_PYTHON), "-m", "PyInstaller", "--version"],
                            capture_output=True, text=True, encoding="utf-8", errors="replace",
                            check=False)
    if result.returncode != 0:
        return None
    return parse_pyinstaller_version(result.stdout + result.stderr)


def ensure_pyinstaller(pinned: str) -> str:
    current = installed_pyinstaller_version()
    if current == pinned:
        print(f"pyinstaller: {pinned} already installed in {VENV_PYTHON.parent.parent.name}")
        return current
    wheel = fetch.fetch(PYINSTALLER_KEY)
    print(f"pyinstaller: installing {wheel.name} into {VENV_PYTHON}")
    result = subprocess.run([str(VENV_PYTHON), "-m", "pip", "install", str(wheel)],
                            capture_output=True, text=True, encoding="utf-8", errors="replace",
                            check=False)
    print((result.stdout + result.stderr).strip(), flush=True)
    if result.returncode != 0:
        raise PackagingError(f"pip install {wheel.name} failed with exit code {result.returncode}")
    current = installed_pyinstaller_version()
    if current != pinned:
        raise PackagingError(f"PyInstaller reports {current!r} after the install, pinned {pinned!r}")
    print(f"  python -m PyInstaller --version reports {current}")
    return current


def pyinstaller_smoke() -> None:
    """Build and run a one-folder app to prove the bootloader starts for a standard user."""
    work_dir = TOOLCHAIN_ROOT / "pyinstaller-smoke-work"
    shutil.rmtree(work_dir, ignore_errors=True)
    shutil.rmtree(PYINSTALLER_SMOKE_DIR, ignore_errors=True)
    work_dir.mkdir(parents=True, exist_ok=True)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    script = work_dir / "spells_pyinstaller_smoke.py"
    script.write_text(SMOKE_APP_SOURCE, encoding="utf-8")

    args = pyinstaller_args(VENV_PYTHON, script, dist_dir=OUT_DIR, work_dir=work_dir,
                            name=SMOKE_APP_NAME)
    print("+ " + " ".join(args), flush=True)
    result = subprocess.run(args, cwd=str(work_dir), capture_output=True, text=True,
                            encoding="utf-8", errors="replace", check=False)
    output = (result.stdout + result.stderr).strip()
    if output:
        print(output, flush=True)
    if result.returncode != 0:
        raise PackagingError(f"PyInstaller failed with exit code {result.returncode}")
    exe = PYINSTALLER_SMOKE_DIR / f"{SMOKE_APP_NAME}.exe"
    if not exe.is_file():
        raise PackagingError(f"{exe} is missing after the PyInstaller build")

    run = toolchain.run_tool([str(exe)], cwd=PYINSTALLER_SMOKE_DIR,
                             env=toolchain.clean_windows_env())
    if SMOKE_APP_MARKER not in run.stdout:
        raise PackagingError(f"the smoke app printed {run.stdout!r}")
    print(f"  {exe.name} ran and printed: {run.stdout.strip()}")
    shutil.rmtree(PYINSTALLER_SMOKE_DIR, ignore_errors=True)
    shutil.rmtree(work_dir, ignore_errors=True)
    print(f"  removed {PYINSTALLER_SMOKE_DIR} and the PyInstaller work directory")


# ----------------------------------------------------------------------------- main


def main(argv=None) -> int:
    import argparse

    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.parse_args(argv)

    try:
        missing = missing_parts(TOOLCHAIN_ROOT)
        print(f"parts to install: {', '.join(sorted(missing)) if missing else 'none'}")
        ensure_innoextract()
        ensure_innosetup()
        inno_pin = pinned_version(INNO_SETUP_KEY)
        print("inno setup checks:")
        verify_iscc(inno_pin)
        compile_smoke_installer(inno_pin)
        print("pyinstaller:")
        ensure_pyinstaller(pinned_version(PYINSTALLER_KEY))
        pyinstaller_smoke()
    except (PackagingError, toolchain.BootstrapError, fetch.PinError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    toolchain.report_elevation()
    print(f"packaging toolchain ready in {TOOLCHAIN_ROOT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
